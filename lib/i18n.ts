export const LANGS = ["nl", "en", "fr", "de", "es"] as const;
export type Lang = (typeof LANGS)[number];
export const LANG_COOKIE = "la-lang";
export const isLang = (v: unknown): v is Lang => LANGS.includes(v as Lang);
export const HTML_LANG: Record<Lang, string> = { nl: "nl-BE", en: "en", fr: "fr-BE", de: "de", es: "es" };

/** Picks the first supported language from an Accept-Language header or navigator.languages. */
export function detectLang(prefs: readonly string[] | string | null | undefined): Lang {
  const list = typeof prefs === "string" ? prefs.split(",").map((p) => p.split(";")[0]) : prefs ?? [];
  for (const p of list) {
    const code = p.trim().slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return "nl";
}

